/**
 * Formelkarten: kurz erklärt, was hinter einem Schritt steckt. In der Erklärung kann man einen Schritt
 * antippen und bekommt die passende Karte; beim Tipp-Knopf kommt nur die Formel, ohne die Lösung zu verraten.
 * Gefunden werden die Karten über Stichwörter im Lösungsweg (beide Sprachen).
 */
@Immutable
class Concept(
