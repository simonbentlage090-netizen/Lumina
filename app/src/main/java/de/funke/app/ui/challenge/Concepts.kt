    val subject: Subject,
    private val titleDe: String,
    private val titleEn: String,
    val formula: String,
    private val textDe: String,
    private val textEn: String,
    /** Stichwörter, an denen man die Karte im Lösungsweg erkennt (klein geschrieben vergleichen). */
    val keys: List<String>,
) {
    val title: String get() = tr(titleDe, titleEn)
    val text: String get() = tr(textDe, textEn)
}

